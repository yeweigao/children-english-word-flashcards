function todayKey(): string {
  const d = new Date();
  const m = `${d.getMonth() + 1}`.padStart(2, "0");
  const day = `${d.getDate()}`.padStart(2, "0");
  return `${d.getFullYear()}-${m}-${day}`;
}

function todayStartMs(): number {
  const d = new Date();
  d.setHours(0, 0, 0, 0);
  return d.getTime();
}

/** Shrink a homework photo to a readable size and encode it as JPEG
 *  base64 for the vision reader. The photo is stored on the server
 *  only while its find job runs and is deleted the moment the job
 *  finishes — only the word list it produces stays. */
async function fileToJpegBase64(
  file: File,
): Promise<{ dataBase64: string; mimeType: "image/jpeg" }> {
  const url = URL.createObjectURL(file);
  try {
    const img = await new Promise<HTMLImageElement>((resolve, reject) => {
      const el = new Image();
      el.onload = () => resolve(el);
      el.onerror = () => reject(new Error("这张照片打不开"));
      el.src = url;
    });
    const maxSide = 1600;
    const scale = Math.min(
      1,
      maxSide / Math.max(img.naturalWidth, img.naturalHeight, 1),
    );
    const w = Math.max(1, Math.round(img.naturalWidth * scale));
    const h = Math.max(1, Math.round(img.naturalHeight * scale));
    const canvas = document.createElement("canvas");
    canvas.width = w;
    canvas.height = h;
    const ctx2d = canvas.getContext("2d");
    if (!ctx2d) throw new Error("这台设备处理不了照片");
    ctx2d.drawImage(img, 0, 0, w, h);
    const dataUrl = canvas.toDataURL("image/jpeg", 0.85);
    const comma = dataUrl.indexOf(",");
    return {
      dataBase64: comma >= 0 ? dataUrl.slice(comma + 1) : dataUrl,
      mimeType: "image/jpeg",
    };
  } finally {
    URL.revokeObjectURL(url);
  }
}

/* ---------------- speech: the product's own voice ----------------
   Pronunciation is generated by the product itself: the server
   synthesizes each word or sentence once with a high-quality voice
   and caches the clip, so every device plays the same good recording
   and repeat plays are instant. (Device voices were dropped: iOS
   never exposes its downloaded Enhanced/Premium voices to web pages,
   so the picker could only ever offer the plain ones.)
   The parent picks British or American in 档案 页顶部的「发音」;
   British is the default — it matches the IPA printed on the cards. */

type Accent = "gb" | "us";
const ACCENT_KEY = "flashcard-accent";

function accentPref(): Accent {
  try {
    return window.localStorage.getItem(ACCENT_KEY) === "us" ? "us" : "gb";
  } catch {
    return "gb";
  }
}

function saveAccentPref(a: Accent) {
  try {
    window.localStorage.setItem(ACCENT_KEY, a);
  } catch {
    /* ignore */
  }
}

const speechUrlCache = new Map<string, string>();
let currentAudio: HTMLAudioElement | null = null;
let speakSeq = 0;

/* Celebration never crosses a screen. Praise (banner + voice) belongs
   to the beat that earned it — the front-face tap — and must finish
   inside that beat. advanceFlow() runs on EVERY step transition
   (flip, card beats, dig continue, exit) and enforces both halves
   of that rule: flowStamp voids a praise clip that has not started
   sounding yet, and stopCurrentAudio() cuts off one that is ALREADY
   playing — without the second half, a fast flip let the front's
   praise keep talking over the card back until it finished. */
let flowStamp = 0;

/** Hard-stop whatever clip is sounding right now: pause it, rewind
 *  it, and drop the reference so nothing can resume it. Also bumps
 *  speakSeq, so a playSpeech call still awaiting its URL resolves as
 *  superseded instead of starting a fresh element after the stop. */
function stopCurrentAudio() {
  speakSeq += 1;
  const audio = currentAudio;
  currentAudio = null;
  if (audio) {
    try {
      audio.pause();
      audio.currentTime = 0;
    } catch {
      /* element already gone — nothing to stop */
    }
  }
}

function advanceFlow() {
  flowStamp += 1;
  stopCurrentAudio();
}

/** Play the product recording for `text` in the given accent. Resolves
 *  false when the clip could not be fetched or played (dictation then
 *  falls back to asking a parent to read aloud). `guard`, when given,
 *  is re-checked after the clip URL resolves: if it no longer holds,
 *  the clip is dropped without playing (returns true — superseded is
 *  not a playback failure). */
async function playSpeech(
  text: string,
  accent: Accent,
  retry = true,
  guard?: () => boolean,
): Promise<boolean> {
  const clean = text.trim().replace(/\s+/g, " ");
  if (!clean) return false;
  const seq = ++speakSeq;
  const cacheKey = `${accent}|${clean}`;
  try {
    let url = speechUrlCache.get(cacheKey);
    if (!url) {
      const res = await api.getSpeech({ text: clean, accent });
      url = res.url;
      speechUrlCache.set(cacheKey, url);
    }
    if (seq !== speakSeq) return true; // a newer tap took over
    if (guard && !guard()) return true; // its moment has passed — drop it
    currentAudio?.pause();
    const audio = new Audio(url);
    currentAudio = audio;
    await audio.play();
    return true;
  } catch {
    // A cached URL may have gone stale — drop it and fetch a fresh one
    // once. But if this call was superseded meanwhile (a newer tap, or
    // advanceFlow() stopped playback at a step change and bumped
    // speakSeq), the interruption is final: never restart the clip on
    // the next screen.
    if (retry && seq === speakSeq) {
      speechUrlCache.delete(cacheKey);
      return playSpeech(text, accent, false, guard);
    }
    return seq !== speakSeq;
  }
}

/* Pre-generate + cache the small rotation of praise/comfort clips up
   front (app open, session start), so a correct answer's voice is
   already on the device and can fire in the SAME frame as the visual
   feedback — never synthesized or fetched at the moment of the tap. */
const speechPreloadInFlight = new Set<string>();
function preloadSpeechClip(text: string) {
  const accent = accentPref();
  const clean = text.trim().replace(/\s+/g, " ");
  if (!clean) return;
  const key = `${accent}|${clean}`;
  if (speechUrlCache.has(key) || speechPreloadInFlight.has(key)) return;
  speechPreloadInFlight.add(key);
  api
    .getSpeech({ text: clean, accent })
    .then((res) => {
      speechUrlCache.set(key, res.url);
    })
    .catch(() => {
      /* warming is best-effort; a later play fetches for real */
    })
    .finally(() => {
      speechPreloadInFlight.delete(key);
    });
}

function speak(text: string, onFail?: () => void) {
  void playSpeech(text, accentPref()).then((ok) => {
    if (!ok) onFail?.();
  });
}

/* ---------------- auto read-aloud (parent setting) ----------------
   One parent switch （档案 · 发音设置 · 「打开自动朗读」, stored in
   the settings table, default ON): when on, DISPLAY faces read
   themselves aloud as they appear — the front's birth sentence,
   the card back's word, each example sentence as it reaches the
   top of the deck, a library card's word when the card expands.
   Production faces never auto-read: 拼一拼 and 选词填空 would leak
   the very English being produced, and dictation keeps its own
   play button. Auto-read rides the same speech channel as
   everything else, so it obeys the same discipline: advanceFlow()
   cuts it at every step change, and speakSeq supersession means
   it can never talk over an emotion popup's encouragement voice
   (whichever starts later wins the channel; the praise beat ends
   before the next display face opens). Manual speaker buttons
   always work, switch or no switch.
   This module variable is the runtime copy; the settings table is
   the record. App syncs it from getOverview at open, and the
   settings toggle flips it the moment the parent taps. */
let autoReadOn = true;

function autoReadPref(): boolean {
  return autoReadOn;
}

function setAutoReadPref(v: boolean) {
  autoReadOn = v;
}

function autoSpeak(text: string) {
  if (!autoReadOn) return;
  speak(text);
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Render a sentence with the target word highlighted (or blanked for cloze). */
function HighlightSentence({
  sentence,
  word,
  blank = false,
  className = "",
}: {
  sentence: string;
  word: string;
  blank?: boolean;
  className?: string;
}) {
  const re = new RegExp(`\\b(${escapeRegExp(word)}\\w*)`, "i");
  const m = sentence.match(re);
  if (!m || m.index === undefined) {
    return <span className={className}>{sentence}</span>;
  }
  const before = sentence.slice(0, m.index);
  const hit = m[0] ?? word;
  const after = sentence.slice(m.index + hit.length);
  return (
    <span className={className}>
      {before}
      {blank ? (
        <span className="mx-0.5 inline-block min-w-16 rounded-lg bg-[var(--sun)] px-2 py-0.5 text-center font-bold text-[#7a5b00]">
          ?
        </span>
      ) : (
        <span className="rounded-md bg-[var(--sun)] px-1 font-bold text-[#7a5b00]">
          {hit}
        </span>
      )}
      {after}
    </span>
  );
}

