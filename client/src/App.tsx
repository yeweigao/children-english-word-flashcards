    (hasCards && dueDone ? 1 : 0) +
    (hasCards && newDone ? 1 : 0) +
    (hasLearning && digDone ? 1 : 0) +
    (allDone ? 1 : 0);
  const currentKey: "review" | "new" | "dig" | "finish" | null = !hasCards
