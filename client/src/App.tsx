/* ---------------- spoken praise + pop-up feedback ----------------
   Duolingo's emotional core, kept honest: the cheer is a VOICE plus a
   sheet that pops up from the bottom of the screen, and it only ever
   follows a real learning event — a right answer, a word said aloud
   correctly, a graduation. The spoken line is English on purpose: the
   praise doubles as listening input, and the product's own voice says
   it, so it sounds the same on every device. Lines rotate so it never
   sounds canned. A wrong answer gets a spoken "good try" first, then
   the correct answer — never silence, never a penalty sound. */

const PRAISE_SPOKEN = [
  "Great job!",
  "Well done!",
  "You did it!",
  "Amazing!",
  "Super work!",
];
const COMFORT_SPOKEN = ["Good try!", "Almost there!", "You can do it!"];

function spokenLine(lines: string[], seed: number): string {
  return lines[Math.abs(seed) % lines.length] ?? lines[0]!;
}

/* Spoken feedback is stamped with the current flow step. The clip
   cache is pre-warmed (preloadFeedbackVoices), so the voice starts in
   the same frame as the visual feedback; and the moment the flow
   moves on (advanceFlow at the flip / continue / exit), a clip that
   has not started yet is dropped AND one already sounding is cut off
   mid-line — praise never replays or finishes itself on the next
   screen. */
function speakFeedback(correct: boolean, seed: number) {
  const stamp = flowStamp;
  const line = spokenLine(correct ? PRAISE_SPOKEN : COMFORT_SPOKEN, seed);
  void playSpeech(line, accentPref(), true, () => stamp === flowStamp);
}

/** Warm every praise/comfort clip for the current accent. Called at
 *  app open and at session start, long before the first answer. */
function preloadFeedbackVoices() {
  for (const line of [...PRAISE_SPOKEN, ...COMFORT_SPOKEN]) {
    preloadSpeechClip(line);
  }
}

