/* ---------------- find-flow persistence ----------------
   Leaving must not lose the flow — and now it genuinely cannot: the
   read is a SERVER-side job. The parent approved temporary server
   storage of the photos (识别完立刻删), so startFindJob returns a
   jobId at once and the server finishes the read whether or not this
   page stays open. The local snapshot only mirrors presentation
   state: the active jobId while a job runs (reopening adopts it and
   keeps polling), and the full result once the cards are made. A
   jobId whose result has been seen and dismissed is remembered so a
   reopened page does not resurrect it. */
const FIND_SNAPSHOT_KEY = "find-flow-v1";
const FIND_DISMISSED_KEY = "find-job-dismissed-v1";

type FindSnapshot = {
  stage: "analyzing" | "done";
  pageCount: number;
  startedAt: number;
  made: MadeState | null;
  addedOptional: string[];
  jobId?: string | null;
};

function loadDismissedJobId(): string | null {
  try {
    return window.localStorage.getItem(FIND_DISMISSED_KEY);
  } catch {
    return null;
  }
}

function saveDismissedJobId(id: string) {
  try {
    window.localStorage.setItem(FIND_DISMISSED_KEY, id);
  } catch {
    /* ignore */
  }
}

function loadFindSnapshot(): FindSnapshot | null {
  try {
    const raw = window.localStorage.getItem(FIND_SNAPSHOT_KEY);
    if (!raw) return null;
    const v = JSON.parse(raw) as FindSnapshot;
    if (v && (v.stage === "analyzing" || v.stage === "done")) return v;
  } catch {
    /* ignore */
  }
  return null;
}

function saveFindSnapshot(s: FindSnapshot) {
  try {
    window.localStorage.setItem(FIND_SNAPSHOT_KEY, JSON.stringify(s));
  } catch {
    /* ignore */
  }
}

function clearFindSnapshot() {
  try {
    window.localStorage.removeItem(FIND_SNAPSHOT_KEY);
  } catch {
    /* ignore */
  }
}

