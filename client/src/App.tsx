/* ---------------- session action bar ----------------
   A session screen is a full-height column: progress header, ONE
   card region that fills the middle, and a bottom action bar of a
   RESERVED, always-equal height. Every face/step sends its flow
   buttons （看例句 / 来挖题 / 检查 / 挖出来了·还没） into that bar
   through this portal, so the primary action always sits in the
   same thumb spot at the bottom of the screen and the card region
   above it never changes height between beats — the card is one
   height on every face. Answer controls that ARE the exercise
   (meaning options, word tiles) stay inside the card; only flow
   actions move to the bar. When a beat has no flow action (the
   front guess, the choice warm-up), the bar simply stays empty at
   the same height. The feedback sheet (fixed, z-40) covers the bar
   while it is up, and its 继续 is the action then. */
const ActionBarContext = createContext<{ node: HTMLElement | null }>({
  node: null,
});

function ActionBarSlot({ children }: { children: ReactNode }) {
  const { node } = useContext(ActionBarContext);
  if (!node) return <>{children}</>;
  return createPortal(children, node);
}

