type Tab = "home" | "find" | "cards" | "archive";

export function App() {
  const queryClient = useQueryClient();
  const [tab, setTab] = useState<Tab>("home");
  const [session, setSession] = useState<null | {
    kind: "due" | "new" | "dig";
    cards: Card[];
  }>(null);
  const day = todayKey();

  const overview = useQuery({
    queryKey: ["overview", day],
    queryFn: () => api.getOverview({ day }),
  });
  const incentives = useQuery({
    queryKey: ["incentives", day],
    queryFn: () => api.getIncentives({ day }),
  });
  const cardsQ = useQuery({
    queryKey: ["cards"],
    queryFn: () => api.listCards({}),
  });
  const exampleQ = useQuery({
    queryKey: ["example"],
    queryFn: () => api.getExamplePage({}),
  });

  const startMut = useMutation({
    mutationFn: async (kind: "due" | "new") =>
      await api.getStudyQueue({ kind, limit: 10 }),
    onSuccess: (res, kind) => {
      if (res.cards.length > 0) setSession({ kind, cards: res.cards });
    },
  });
  const startDigMut = useMutation({
    mutationFn: async () => await api.getDigQueue({ limit: 10 }),
    onSuccess: (res) => {
      if (res.cards.length > 0)
        setSession({ kind: "dig", cards: res.cards });
    },
  });

  const exitSession = () => {
    advanceFlow();
    setSession(null);
    queryClient.invalidateQueries({ queryKey: ["overview"] });
    queryClient.invalidateQueries({ queryKey: ["incentives"] });
    queryClient.invalidateQueries({ queryKey: ["cards"] });
    queryClient.invalidateQueries({ queryKey: ["archive"] });
  };

  // Warm the praise/comfort clips at app open — celebration voices
  // are pre-generated and cached, never fetched at the answer tap.
  useEffect(() => {
    preloadFeedbackVoices();
  }, []);

  // The settings table is the record for the auto-read switch;
  // sync its value into the runtime copy whenever the overview
  // (re)loads — at open, and after the parent toggles it in 档案.
  useEffect(() => {
    if (overview.data) setAutoReadPref(overview.data.autoRead);
  }, [overview.data]);

  const existingWords = useMemo(
    () =>
      new Set((cardsQ.data?.cards ?? []).map((c) => c.word.toLowerCase())),
    [cardsQ.data],
  );

  if (session) {
    return (
      <div className="min-h-screen overflow-x-clip bg-[var(--bg)]">
        <SafeAreaTopScrim backgroundColor="var(--bg)" />
        {session.kind === "dig" ? (
          <DigSession cards={session.cards} onExit={exitSession} />
        ) : (
          <StudySession
            kind={session.kind}
            cards={session.cards}
            allCards={cardsQ.data?.cards ?? session.cards}
            onExit={exitSession}
          />
        )}
      </div>
    );
  }

  const nav: { key: Tab; label: string; icon: ReactNode }[] = [
    { key: "home", label: "复习", icon: <IconHome /> },
    { key: "find", label: "找词", icon: <IconCamera /> },
    { key: "cards", label: "词卡", icon: <IconLayers /> },
    { key: "archive", label: "档案", icon: <IconHistory /> },
  ];

  return (
    <div className="min-h-screen overflow-x-clip bg-[var(--bg)]">
      <SafeAreaTopScrim backgroundColor="var(--bg)" />
      <main className="mx-auto w-full max-w-2xl overflow-x-clip px-4 pb-32 pt-5">
        {tab === "home" &&
          (overview.isPending ? (
            <p className="py-16 text-center text-[var(--dim)]">
              正在准备今天的小路…
            </p>
          ) : overview.data ? (
            <HomeScreen
              overview={overview.data}
              incentives={incentives.data ?? null}
              starting={startMut.isPending || startDigMut.isPending}
              onStart={(kind) => startMut.mutate(kind)}
              onStartDig={() => startDigMut.mutate()}
              onGotoFind={() => setTab("find")}
              onGotoCards={() => setTab("cards")}
            />
          ) : (
            <p className="py-16 text-center font-bold text-[var(--coral)]">
              加载失败，拉一下重试。
            </p>
          ))}

        {tab === "find" &&
          (exampleQ.data && overview.data ? (
            <FindScreen
              level={overview.data.level}
              page={exampleQ.data}
              existingWords={existingWords}
              onStartLearning={() => startMut.mutate("new")}
            />
          ) : (
            <p className="py-16 text-center text-[var(--dim)]">
              正在摊开作业页…
            </p>
          ))}

        {tab === "cards" && (
          <CardsScreen cards={cardsQ.data?.cards ?? []} />
        )}

        {tab === "archive" && <ArchiveScreen />}
      </main>

      <nav
        aria-label="主导航"
        className="fixed inset-x-0 bottom-0 border-t-2 border-[var(--border)] bg-[var(--surface)] pb-safe"
      >
        <div className="mx-auto grid max-w-2xl grid-cols-4">
          {nav.map((n) => (
            <button
              key={n.key}
              type="button"
              aria-current={tab === n.key ? "page" : undefined}
              onClick={() => setTab(n.key)}
              className={`flex flex-col items-center gap-0.5 py-2.5 font-bold ${
                tab === n.key
                  ? "text-[var(--accent-deep)]"
                  : "text-[var(--dim)]"
              }`}
            >
              {n.icon}
              <span className="flex items-center gap-1 text-xs">
                {n.label}
                {(n.key === "find" || n.key === "archive") && (
                  <span className="rounded-full bg-[#fff3c4] px-1.5 py-px text-[10px] font-bold text-[#8a6d00]">
                    家长
                  </span>
                )}
              </span>
            </button>
          ))}
        </div>
      </nav>
    </div>
  );
}
